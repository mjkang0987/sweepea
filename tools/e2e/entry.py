import sys
from playwright.sync_api import sync_playwright
B='http://localhost:4321'; OUT='/home/claude/sweepea/tools/e2e/'
def check(c,msg):
    if not c: print('FAIL',msg); sys.exit(1)
    print('ok',msg)
with sync_playwright() as p:
    b=p.chromium.launch()
    def ctx(scheme='light'):
        return b.new_context(viewport={'width':390,'height':844}, color_scheme=scheme)
    # 1) 외할머니: 이름 → 틀림 → 맞음 → 앨범, 다시 열면 바로 앨범
    c=ctx(); pg=c.new_page()
    pg.goto(B+'/i/Harin001'); pg.screenshot(path=OUT+'1-who.png')
    check(not any(k['name']=='sp_pass' for k in c.cookies()),'이름 화면만 열면 출입증(익명 사용자)을 안 만든다')
    pg.goto(B+'/i/Harin001/password?name='+'가'*13+'&g=g-mat'); check(pg.url.endswith('e=name') and '이름을 1~12자로' in pg.content(),'긴 이름은 되돌리고 안내')
    pg.goto(B+'/i/Harin001')
    pg.get_by_role('button',name='이모').click(); pg.wait_for_url('**/password**')
    check('sp-size-base' in pg.content(),'이모를 잘못 누르면 기본 크기')
    pg.get_by_role('link',name='다른 이름 고르기').click(); pg.wait_for_url('**/i/Harin001')
    check(pg.locator('input[name=size]:checked').count()==0,'이름으로 정한 크기는 저장 안 함(라디오 비어 있음)')
    pg.get_by_role('button',name='외할머니').click(); pg.wait_for_url('**/password**')
    check(pg.get_by_role('heading',name='외할머니 맞으세요?').is_visible(),'비밀번호 화면')
    check('힌트 · 외가 비밀번호' in pg.content(),'힌트 보임')
    check('sp-size-large' in pg.content(),'할머니는 글자 크기 자동 크게')
    check(pg.evaluate("document.activeElement.id")=='pw','비밀번호 칸에 바로 커서')
    pg.fill('#pw','0000'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_load_state()
    check(pg.get_by_role('alert').inner_text().startswith('비밀번호가 맞지 않아요'),'틀리면 안내'); pg.screenshot(path=OUT+'2-wrong.png')
    check(pg.title().startswith('다시 눌러 주세요'),'틀리면 제목에도 알림')
    pg.fill('#pw','1234'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_url('**/album')
    check('하린이 사진' in pg.content(),'앨범 들어감'); pg.screenshot(path=OUT+'3-album.png')
    check('sp-size-large' in pg.content(),'들어간 뒤엔 그 크기로 고정')
    pg.goto(B+'/i/Harin002'); check(pg.url.endswith('/album'),'들어온 기기는 링크 다시 열면 바로 앨범')
    pg.goto(B+'/'); check(pg.url.endswith('/album'),'주소 없이 와도 앨범')
    # 같은 기기로 다른 가족방(도윤이네)
    pg.goto(B+'/i/Doyun001'); check(pg.get_by_role('heading',name='누구세요?').is_visible(),'다른 가족방 링크는 누구세요부터')
    pg.get_by_role('button',name='할머니').click(); pg.wait_for_url('**/password**')
    pg.fill('#pw','9999'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_url('**/album')
    check('하린이·도윤이 사진' in pg.content(),'앨범에 두 가족방이 같이'); pg.screenshot(path=OUT+'3b-album-two.png')
    pg.goto(B+'/i/Doyun001'); check(pg.url.endswith('/album'),'두 번째 가족방 링크도 바로 앨범')
    c.close()
    # 2) 새 이름 큰이모 → 승인 대기
    c=ctx('dark'); pg=c.new_page()
    pg.goto(B+'/i/Harin001'); pg.get_by_text('아주 크게').click(); pg.fill('#who-name','큰이모'); pg.keyboard.press('Enter'); pg.wait_for_url('**/password**')
    check(pg.get_by_role('heading',name='큰이모 맞으세요?').is_visible(),'엔터로 새 이름 제출')
    check('sp-size-xlarge' in pg.content(),'직접 고른 크기(아주 크게)가 먼저')
    pg.fill('#pw','1234'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_url('**/wait')
    check('엄마아빠가 확인하면 다 열려요' in pg.content(),'승인 대기 화면'); pg.screenshot(path=OUT+'4-wait.png')
    pg.goto(B+'/album'); check(pg.url.endswith('/wait'),'승인 전엔 앨범 대신 대기')
    c.close()
    # 3) 3번 틀리면 쉬기
    c=ctx(); pg=c.new_page(); pg.goto(B+'/i/Harin001'); pg.get_by_role('button',name='외할아버지').click(); pg.wait_for_url('**/password**')
    for k in range(3):
        pg.fill('#pw','999%d'%k); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_load_state()
    check('30초 쉬었다가' in pg.content(),'3번째 틀리면 쉬기 안내')
    pg.fill('#pw','1234'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_load_state()
    check('초 뒤에 다시' in pg.content(),'쉬는 중엔 맞아도 대기'); pg.screenshot(path=OUT+'5-locked.png')
    c.close()
    # 4) 기간 지난 링크: 새 이름 칸 없음, 등록 이름은 됨 / 닫힌 앨범 / 없는 주소 / 문자 링크
    c=ctx(); pg=c.new_page(); pg.goto(B+'/i/Harin002')
    check(pg.locator('#who-name').count()==0,'기간 지난 링크엔 새 이름 칸 없음')
    pg.goto(B+'/i/Closed01'); check('앨범이 닫혔어요' in pg.content(),'닫힌 앨범')
    pg.goto(B+'/i/Nope0000'); check('가족에게 받은 주소로' in pg.content(),'없는 주소')
    pg.goto(B+'/i/bad'); check('가족에게 받은 주소로' in pg.content(),'형식 틀린 주소')
    c.close()
    c=ctx(); pg=c.new_page(); pg.goto(B+'/i/Sms00001')
    check(pg.get_by_role('button',name='외할머니').count()==1 and pg.get_by_role('button',name='이모').count()==0 and pg.locator('#who-name').count()==0,'문자 링크는 그 사람만')
    pg.get_by_role('button',name='외할머니').click(); pg.wait_for_url('**/password**'); pg.fill('#pw','1234'); pg.get_by_role('button',name='들어가기').click(); pg.wait_for_url('**/album')
    c.close()
    c=ctx(); pg=c.new_page(); pg.goto(B+'/i/Sms00001'); check('주소 기간이 지났어요' in pg.content(),'쓴 문자 링크는 기간 지남')
    pg.goto(B+'/'); pg.screenshot(path=OUT+'6-nolink.png')
    c.close()
    b.close()
print('ALL OK')
