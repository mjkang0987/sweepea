# 아이 추가·변경, 가족 화면 글자 크기, 계정
from playwright.sync_api import sync_playwright
B='http://localhost:4321'; D='/home/claude/sweepea/tools/e2e/'
def check(c,msg):
    if not c: raise SystemExit('FAIL '+msg)
    print('ok',msg)
with sync_playwright() as p:
    b=p.chromium.launch()
    c=b.new_context(viewport={'width':390,'height':844}); pg=c.new_page()
    def shot(n): pg.screenshot(path=D+'s2-'+n+'.png',full_page=True)
    pg.goto(B+'/login'); pg.get_by_role('link',name='개발용으로 계속하기').click(); pg.wait_for_url('**/setup')
    pg.fill('#child','서아'); pg.fill('#birth','2025-09-17'); pg.get_by_role('button',name='다음').click(); pg.wait_for_url('**/setup/password**')
    pg.fill('#pw','0917'); pg.get_by_role('button',name='시작하기').click(); pg.wait_for_url('**/home')
    pg.goto(B+'/settings'); check(pg.get_by_role('link',name='아이 서아').count()==1,'설정에 아이 줄'); shot('1')
    pg.get_by_role('link',name='아이 서아').click(); pg.wait_for_url('**/settings/children')
    check('생후' in pg.content(),'아이 목록에 생후 개월')
    pg.get_by_role('link',name='아이 추가').click(); pg.wait_for_url('**/children/new')
    pg.fill('#name','  '); pg.fill('#birth','2026-08-30'); pg.evaluate("document.querySelector('#name').removeAttribute('required')")
    pg.get_by_role('button',name='추가').click(); check(pg.get_by_role('alert').inner_text().startswith('이름을'),'빈 이름은 오류')
    check(pg.locator('#name').get_attribute('aria-invalid')=='true','오류 칸 표시')
    pg.fill('#name','도윤'); pg.get_by_role('button',name='추가').click(); pg.wait_for_url('**done=added**')
    check(pg.locator('.sp-p__row',has_text='도윤').count()==1,'아이 추가됨'); shot('2')
    pg.locator('.sp-p__row',has_text='도윤').click(); pg.wait_for_url('**/children/**')
    check(pg.locator('#birth').input_value()=='2026-08-30','변경 화면에 원래 값')
    pg.fill('#name','도윤이'); pg.get_by_role('button',name='저장').click(); pg.wait_for_url('**done=saved**')
    check(pg.locator('.sp-p__row',has_text='도윤이').count()==1,'고친 이름')
    pg.goto(B+'/settings/children/00000000-0000-4000-8000-000000000999'); check(pg.url.endswith('/settings/children'),'없는 아이는 목록으로')
    pg.goto(B+'/upload'); check(pg.get_by_label('도윤이').count()==1,'올리기 화면 아이 고르기에 새 아이')
    # 글자 크기
    pg.goto(B+'/settings'); pg.get_by_role('link',name='가족 화면 글자 크기 관계에 맞춰').click(); pg.wait_for_url('**/text-size')
    t=pg.locator('.sp-p__preview-title'); big=t.evaluate("e=>parseFloat(getComputedStyle(e).fontSize)")
    pg.get_by_label('모두 기본').check(); small=t.evaluate("e=>parseFloat(getComputedStyle(e).fontSize)")
    check(small<big,'미리보기가 고른 크기로 (JS 없이) %.1f→%.1f'%(big,small))
    pg.get_by_label('모두 아주 크게').check(); pg.wait_for_function("document.getElementById('as-live')?.textContent.trim().length>0"); shot('3')
    check(pg.get_by_label('모두 아주 크게').is_checked(),'저장된 크기')
    pg.goto(B+'/settings'); check(pg.get_by_role('link',name='가족 화면 글자 크기 모두 아주 크게').count()==1,'설정에 지금 값')
    pg.goto(B+'/settings/family'); pg.get_by_role('button',name='링크 만들기 (가족)').click(); pg.wait_for_selector('#link-url')
    code=pg.locator('#link-url').input_value().rsplit('/',1)[1]
    g=b.new_context(viewport={'width':390,'height':844}); gp=g.new_page(); gp.goto(B+'/i/'+code)
    check(gp.locator('.sp-size-xlarge').count()>=1 and gp.get_by_label('아주 크게').is_checked(),'누구세요 화면부터 아주 크게')
    gp.fill('#who-name','이모'); gp.get_by_role('button',name='들어가기').click(); gp.wait_for_url('**/password**')
    check(gp.locator('html.sp-size-xlarge, body.sp-size-xlarge, .sp-size-xlarge').count()>=1,'새로 들어오는 가족은 아주 크게')
    # 계정
    pg.goto(B+'/settings'); pg.get_by_role('link',name='로그인 계정').click(); pg.wait_for_url('**/account')
    check('서아 엄마' in pg.content(),'계정에 호칭'); shot('4')
    pg.get_by_role('button',name='로그아웃').click(); pg.wait_for_url('**/login')
    check(True,'로그아웃')
    b.close()
print('ALL OK')
